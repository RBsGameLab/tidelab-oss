using System.Text;

namespace Tidelab.ProtoGen;

/// <summary>
/// Writes a <see cref="Schema"/> as proto3 files, one or more per namespace, that protoc compiles
/// back into code with the client's field numbers, encodings and names:
/// <list type="bullet">
/// <item>package <c>aki.protocol[.sub]</c>, C# namespace <c>Tidelab.Protocol[.Sub]</c>;</item>
/// <item>field and oneof names are the client's property names with the first letter
///   lowered, which protoc turns back into the same property names;</item>
/// <item>enum values are written <c>Enum_Value</c>: proto3 puts enum values in the enclosing
///   scope, where many enums share names like <c>None</c>; protoc's C# generator drops the
///   prefix again.</item>
/// </list>
/// </summary>
public sealed class ProtoWriter(Schema schema)
{
    public const string Package = "aki.protocol";
    public const string CsNamespace = "Tidelab.Protocol";
    public const string Header = "Generated by tools/Tidelab.ProtoGen from the client's Aki.Protocol (3.8). Do not edit.";

    private readonly Dictionary<string, Message> messages = schema.Messages.ToDictionary(m => m.FullName, StringComparer.Ordinal);
    private readonly Dictionary<string, EnumType> enums = schema.Enums.ToDictionary(e => e.FullName, StringComparer.Ordinal);
    public List<string> Problems { get; } = [];

    public static string PackageOf(string ns) => ns.Length == 0 ? Package : $"{Package}.{ns.ToLowerInvariant()}";
    public static string CsNamespaceOf(string ns) => ns.Length == 0 ? CsNamespace : $"{CsNamespace}.{ns}";

    /// <summary>A namespace's file for one layer: aki_protocol.proto, aki_protocol_ai.proto,
    /// aki_protocol_ai.1.proto, ...</summary>
    public static string FileName(string ns, int layer) =>
        (ns.Length == 0 ? "aki_protocol" : $"aki_protocol_{ns.ToLowerInvariant().Replace('.', '_')}")
        + (layer == 0 ? "" : $".{layer}") + ".proto";

    /// <summary>File name → contents.</summary>
    public SortedDictionary<string, string> Write()
    {
        var layer = Layers();
        var files = new SortedDictionary<string, (string Ns, int Layer)>(StringComparer.Ordinal);
        foreach (var (top, l) in layer)
            files[FileName(NamespaceOf(top), l)] = (NamespaceOf(top), l);

        var result = new SortedDictionary<string, string>(StringComparer.Ordinal);
        foreach (var (file, (ns, l)) in files)
        {
            bool Here(string full) => layer[Top(full)] == l && NamespaceOf(full) == ns;
            var imports = new SortedSet<string>(StringComparer.Ordinal);
            foreach (var m in schema.Messages.Where(m => Here(m.FullName)))
                foreach (var f in m.Fields)
                    foreach (var r in new[] { f.Type.Ref, f.Key?.Ref })
                        if (r is not null && !Here(r))
                            imports.Add(FileName(NamespaceOf(r), layer[Top(r)]));

            var sb = new StringBuilder();
            sb.Append("// ").Append(Header).Append('\n');
            sb.Append("syntax = \"proto3\";\n\n");
            sb.Append("package ").Append(PackageOf(ns)).Append(";\n\n");
            sb.Append("option csharp_namespace = \"").Append(CsNamespaceOf(ns)).Append("\";\n");
            foreach (var dep in imports)
                sb.Append("\nimport \"").Append(dep).Append("\";");
            sb.Append('\n');
            foreach (var e in schema.Enums.Where(e => e.Outer is null && Here(e.FullName)))
                WriteEnum(sb, e, 0);
            foreach (var m in schema.Messages.Where(m => m.Outer is null && Here(m.FullName)))
                WriteMessage(sb, m, 0);
            result[file] = sb.ToString();
        }
        return result;
    }

    private string NamespaceOf(string fullName) =>
        messages.TryGetValue(fullName, out var m) ? m.Namespace : enums[fullName].Namespace;

    /// <summary>The top-level type a nested type lives in (itself for a top-level type).</summary>
    private string Top(string fullName)
    {
        while (true)
        {
            string? outer = messages.TryGetValue(fullName, out var m) ? m.Outer : enums[fullName].Outer;
            if (outer is null)
                return fullName;
            fullName = outer;
        }
    }

    /// <summary>
    /// Top-level type → layer. Namespaces use each other's types both ways (Ai and the root
    /// namespace do), and proto files may not import each other, so a namespace is split into
    /// layers: a type sits one layer above the highest-layer type it uses from another
    /// namespace, and at least as high as what it uses from its own. Imports then only go to
    /// a lower layer or to the same file. Types that use each other round a loop share a
    /// layer, so a loop across namespaces cannot be split and is reported.
    /// </summary>
    private Dictionary<string, int> Layers()
    {
        var deps = new Dictionary<string, HashSet<string>>(StringComparer.Ordinal);
        foreach (var t in schema.Messages.Select(m => m.FullName).Concat(schema.Enums.Select(e => e.FullName)))
            deps.TryAdd(Top(t), new HashSet<string>(StringComparer.Ordinal));
        foreach (var m in schema.Messages)
            foreach (var f in m.Fields)
                foreach (var r in new[] { f.Type.Ref, f.Key?.Ref })
                    if (r is not null && Top(r) != Top(m.FullName))
                        deps[Top(m.FullName)].Add(Top(r));

        var sccs = StronglyConnected(deps);
        var sccOf = new Dictionary<string, int>(StringComparer.Ordinal);
        for (int i = 0; i < sccs.Count; i++)
            foreach (var t in sccs[i])
                sccOf[t] = i;
        foreach (var scc in sccs.Where(c => c.Select(NamespaceOf).Distinct().Count() > 1))
            Problems.Add("types in different namespaces use each other: " + string.Join(", ", scc.Order(StringComparer.Ordinal)));

        // Tarjan yields a component after every component it reaches: one pass in order.
        var layerOf = new int[sccs.Count];
        for (int i = 0; i < sccs.Count; i++)
            foreach (var t in sccs[i])
                foreach (var d in deps[t])
                    if (sccOf[d] != i)
                        layerOf[i] = Math.Max(layerOf[i], layerOf[sccOf[d]] + (NamespaceOf(d) == NamespaceOf(t) ? 0 : 1));
        // Number each namespace's layers 0, 1, 2 ... (file names), keeping their order.
        var rank = deps.Keys.GroupBy(NamespaceOf)
            .SelectMany(g => g.Select(t => layerOf[sccOf[t]]).Distinct().Order().Select((l, i) => (g.Key, l, i)))
            .ToDictionary(x => (x.Key, x.l), x => x.i);
        return deps.Keys.ToDictionary(t => t, t => rank[(NamespaceOf(t), layerOf[sccOf[t]])], StringComparer.Ordinal);
    }

    /// <summary>Tarjan's algorithm, iterative (the type graph is deep); components come out
    /// after the components they reach.</summary>
    private static List<List<string>> StronglyConnected(Dictionary<string, HashSet<string>> deps)
    {
        var index = new Dictionary<string, int>(StringComparer.Ordinal);
        var low = new Dictionary<string, int>(StringComparer.Ordinal);
        var onStack = new HashSet<string>(StringComparer.Ordinal);
        var stack = new Stack<string>();
        var result = new List<List<string>>();
        var work = new Stack<(string Node, IEnumerator<string> Next)>();

        void Visit(string n)
        {
            index[n] = low[n] = index.Count;
            stack.Push(n);
            onStack.Add(n);
            work.Push((n, deps[n].Order(StringComparer.Ordinal).GetEnumerator()));
        }

        foreach (var start in deps.Keys.Order(StringComparer.Ordinal))
        {
            if (index.ContainsKey(start))
                continue;
            Visit(start);
            while (work.Count > 0)
            {
                var (n, next) = work.Peek();
                if (next.MoveNext())
                {
                    var d = next.Current;
                    if (!index.ContainsKey(d))
                        Visit(d);
                    else if (onStack.Contains(d))
                        low[n] = Math.Min(low[n], index[d]);
                    continue;
                }
                work.Pop();
                if (work.Count > 0)
                    low[work.Peek().Node] = Math.Min(low[work.Peek().Node], low[n]);
                if (low[n] == index[n])
                {
                    var scc = new List<string>();
                    string x;
                    do
                    {
                        x = stack.Pop();
                        onStack.Remove(x);
                        scc.Add(x);
                    } while (x != n);
                    result.Add(scc);
                }
            }
        }
        return result;
    }

    private static string Lower(string name) => char.ToLowerInvariant(name[0]) + name[1..];

    private void WriteEnum(StringBuilder sb, EnumType e, int depth)
    {
        string pad = new(' ', depth * 2);
        sb.Append('\n').Append(pad).Append("enum ").Append(e.Name).Append(" {\n");
        if (e.Values.Select(v => v.Value).Distinct().Count() != e.Values.Count)
            sb.Append(pad).Append("  option allow_alias = true;\n");
        // proto3: the first value must be zero.
        var ordered = e.Values.Where(v => v.Value == 0).Take(1)
            .Concat(e.Values.Where(v => v.Value != 0).Concat(e.Values.Where(v => v.Value == 0).Skip(1)))
            .ToList();
        if (ordered.Count == 0 || ordered[0].Value != 0)
            Problems.Add($"enum {e.FullName} has no zero value");
        foreach (var (name, value) in ordered)
            sb.Append(pad).Append("  ").Append(e.Name).Append('_').Append(name).Append(" = ").Append(value).Append(";\n");
        sb.Append(pad).Append("}\n");
    }

    private void WriteMessage(StringBuilder sb, Message m, int depth)
    {
        string pad = new(' ', depth * 2);
        sb.Append('\n').Append(pad).Append("message ").Append(m.Name).Append(" {\n");
        var writtenOneofs = new HashSet<string>(StringComparer.Ordinal);
        foreach (var f in m.Fields)
        {
            if (f.Oneof is null)
            {
                sb.Append(pad).Append("  ").Append(FieldLine(m, f)).Append('\n');
                continue;
            }
            if (!writtenOneofs.Add(f.Oneof))
                continue;
            sb.Append(pad).Append("  oneof ").Append(Lower(f.Oneof)).Append(" {\n");
            foreach (var member in m.Fields.Where(x => x.Oneof == f.Oneof))
                sb.Append(pad).Append("    ").Append(FieldLine(m, member)).Append('\n');
            sb.Append(pad).Append("  }\n");
        }
        foreach (var o in m.Oneofs.Where(o => !writtenOneofs.Contains(o)))
            Problems.Add($"{m.FullName}: oneof {o} has no fields");
        foreach (var e in schema.Enums.Where(e => e.Outer == m.FullName))
            WriteEnum(sb, e, depth + 1);
        foreach (var n in schema.Messages.Where(n => n.Outer == m.FullName))
            WriteMessage(sb, n, depth + 1);
        sb.Append(pad).Append("}\n");
    }

    private string FieldLine(Message m, Field f)
    {
        string type = f.Label == Label.Map
            ? $"map<{TypeName(m, f.Key!)}, {TypeName(m, f.Type)}>"
            : TypeName(m, f.Type);
        string prefix = f.Label switch
        {
            Label.Optional => "optional ",
            Label.Repeated => "repeated ",
            _ => "",
        };
        string options = f.Label == Label.Repeated && f.Type.Packable && !f.Packed ? " [packed = false]" : "";
        return $"{prefix}{type} {Lower(f.Name)} = {f.Number}{options};";
    }

    /// <summary>
    /// A type reference as protoc should resolve it from inside <paramref name="from"/>: the
    /// relative name within the same namespace unless a type nested in <paramref name="from"/>
    /// or its outer messages has the same first name; otherwise the fully qualified name.
    /// </summary>
    private string TypeName(Message from, ValueType t)
    {
        if (t.Ref is null)
            return t.Kind.ToString().ToLowerInvariant();
        string ns = NamespaceOf(t.Ref);
        string local = ns.Length == 0 ? t.Ref : t.Ref[(ns.Length + 1)..];
        if (ns == from.Namespace && !Shadowed(from, local.Split('.')[0]))
            return local;
        return "." + PackageOf(ns) + "." + local;
    }

    private bool Shadowed(Message from, string first)
    {
        for (Message? m = from; m is not null; m = m.Outer is null ? null : messages[m.Outer])
        {
            string prefix = m.FullName + "." + first;
            if (messages.ContainsKey(prefix) || enums.ContainsKey(prefix))
                return true;
        }
        return false;
    }
}
