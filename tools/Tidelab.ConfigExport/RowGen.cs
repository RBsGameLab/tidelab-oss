using System.Text;
using System.Text.Json;

namespace Tidelab.ConfigExport;

/// <summary>Writes the C# (Tidelab.Data) or Go (server/internal/data) row types for the tables of
/// specs/data-tables.tsv and the DataTables type that holds, loads and indexes them. A type has
/// only the fields the tsv lists (what the server reads; the JSON's other fields are ignored), from
/// the client's schema where it has the table, otherwise from the tsv. Each type's Fields method
/// hands each field to a visitor with its JSON name and codec. A string field becomes a JSON value
/// when the exported data holds JSON in it (the exporter writes JSON text out as JSON), and keeps
/// only the paths the tsv lists inside it (a mask).</summary>
public sealed class RowGen(FlatSchema schema, string binData)
{
    private static readonly HashSet<string> Keywords =
    [
        "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char", "checked", "class", "const",
        "continue", "decimal", "default", "delegate", "do", "double", "else", "enum", "event", "explicit",
        "extern", "false", "finally", "fixed", "float", "for", "foreach", "goto", "if", "implicit", "in", "int",
        "interface", "internal", "is", "lock", "long", "namespace", "new", "null", "object", "operator", "out",
        "override", "params", "private", "protected", "public", "readonly", "ref", "return", "sbyte", "sealed",
        "short", "sizeof", "stackalloc", "static", "string", "struct", "switch", "this", "throw", "true", "try",
        "typeof", "uint", "ulong", "unchecked", "unsafe", "ushort", "using", "virtual", "void", "volatile", "while",
    ];

    private static readonly HashSet<string> GoKeywords =
    [
        "break", "case", "chan", "const", "continue", "default", "defer", "else", "fallthrough", "for",
        "func", "go", "goto", "if", "import", "interface", "map", "package", "range", "return", "select",
        "struct", "switch", "type", "var",
    ];

    /// <summary>Tables whose key column is not unique: no key index is generated, DataTables
    /// indexes them by hand (LevelEntityConfig by map and id, specs/data-tables.md §2).</summary>
    private static readonly HashSet<string> ByHand = ["LevelEntityConfig"];

    /// <summary>(type, field) pairs whose values in the data are JSON, not text.</summary>
    private readonly HashSet<(string, string)> jsonFields = [];
    /// <summary>The fields of each type that the tsv reaches.</summary>
    private readonly Dictionary<string, HashSet<string>> used = [];
    /// <summary>float32 fields the server reads as float64 (the tsv's shape).</summary>
    private readonly HashSet<(string, string)> widened = [];
    /// <summary>The types read whole (UseAll).</summary>
    private readonly HashSet<string> whole = [];
    /// <summary>The paths read inside each JSON field, relative to its value.</summary>
    private readonly Dictionary<(string Type, string Field), SortedSet<string>> masks = [];
    private List<(string Table, string Key)>? preparedTables;
    public List<string> Problems { get; } = [];

    private List<(string Table, string Key)> Prepare(TsvSchema tsv)
    {
        if (preparedTables is not null)
            return preparedTables;
        var tables = new List<(string Table, string Key)>();
        foreach (var (t, key) in tsv.Tables)
        {
            // The client's schema where it has the table; otherwise the fields of the tsv.
            if (!schema.Tables.ContainsKey(t))
                tsv.AddTypes(t, schema);
            else if (!schema.Lenient.Contains(t))
                Scan(t);
            tables.Add((t, key));
        }
        foreach (var l in tsv.Lines)
            Use(l.Table, l.Path, l.Path, l.Shape);
        // A type read whole keeps its JSON fields whole too.
        foreach (var k in masks.Keys.Where(k => whole.Contains(k.Type)).ToList())
            masks[k].Clear();
        foreach (var (t, key) in tables)
            if (!used.TryGetValue(t, out var u) || !u.Contains(key))
                Problems.Add($"{t}: key column {key} is not a field it reads");
        return preparedTables = tables;
    }

    public string Generate(TsvSchema tsv)
    {
        var tables = Prepare(tsv);
        if (Problems.Count > 0)
            return "";
        var sb = new StringBuilder();
        sb.Append("""
            // <auto-generated>
            // Written by tools/Tidelab.ConfigExport (configexport gen) from the client's config schema
            // (Aki/JavaScript/Core/Define), the exported JSON and specs/data-tables.tsv (the table
            // list, key columns, the fields read, and the fields of the tables the client does not
            // describe). Do not edit: change the tsv or the generator and generate again.
            // </auto-generated>
            #nullable enable
            using Tidelab.Data.Json;
            using Tidelab.Data.Rows;

            namespace Tidelab.Data.Tables;

            """);
        foreach (var t in used.Keys.Order(StringComparer.Ordinal))
            WriteType(sb, schema.Tables[t]);
        foreach (var ((type, field), paths) in masks.OrderBy(kv => kv.Key.Type + "." + kv.Key.Field, StringComparer.Ordinal))
            WriteMask(sb, type, field, paths);
        WriteDataTables(sb, tables);
        return sb.ToString().Replace("\r\n", "\n");
    }

    /// <summary>Writes the same row types, masks, table list and key indexes in Go (gofmt-clean).</summary>
    public string GenerateGo(TsvSchema tsv)
    {
        var tables = Prepare(tsv);
        if (Problems.Count > 0)
            return "";
        var sb = new StringBuilder();
        sb.Append("// Code generated by tools/Tidelab.ConfigExport (configexport gen). DO NOT EDIT.\n\n");
        sb.Append("package data\n\nimport \"time\"\n\n");
        foreach (var t in used.Keys.Order(StringComparer.Ordinal))
            WriteGoType(sb, schema.Tables[t]);
        foreach (var ((type, field), paths) in masks.OrderBy(kv => kv.Key.Type + "." + kv.Key.Field, StringComparer.Ordinal))
            WriteGoMask(sb, type, field, paths);
        WriteGoDataTables(sb, tables);
        return sb.ToString();
    }

    /// <summary>Marks the field a tsv path starts with as used in the type, and follows the rest
    /// of the path into nested tables, map entries, or a JSON field's mask.</summary>
    private void Use(string type, string path, string whole, string shape = "")
    {
        if (!schema.Tables.TryGetValue(type, out var t))
        {
            Problems.Add($"{whole}: no type {type}");
            return;
        }
        int end = path.IndexOfAny(['.', '[', '{']);
        string name = end < 0 ? path : path[..end];
        string rest = end < 0 ? "" : path[end..];
        var f = t.Fields.FirstOrDefault(x => x.Name == name);
        if (f is null)
        {
            Problems.Add($"{whole}: {type} has no field {name}");
            return;
        }
        if (!used.TryGetValue(type, out var u))
            used[type] = u = [];
        u.Add(name);
        if (IsJson(t, f))
        {
            if (!masks.TryGetValue((type, name), out var m))
                masks[(type, name)] = m = new SortedSet<string>(StringComparer.Ordinal);
            if (rest.Length > 0)
                m.Add(NormaliseIndexes(rest));
            return;
        }
        if (f.Map)
        {
            var entry = schema.Tables[f.Table!];
            Use(entry.Name, "Key", whole);
            Use(entry.Name, "Value", whole, rest is "{}" or "{}[]" ? shape : "");
            var value = entry.Fields.First(e => e.Name == "Value");
            if (rest.StartsWith("{}"))
                rest = rest[2..];
            if (value.Vector && rest.StartsWith('['))
                rest = rest[(rest.IndexOf(']') + 1)..];
            if (rest.StartsWith('.') && value.Kind == Kind.Table)
                Use(value.Table!, rest[1..], whole, shape);
            return;
        }
        if (f.Vector && rest.StartsWith('['))
            rest = rest[(rest.IndexOf(']') + 1)..];
        if (rest.Length == 0)
        {
            // The path stops at a nested table (Buff.TagLogic[], an IntArray): read it whole.
            if (f.Kind == Kind.Table)
                UseAll(f.Table!);
            // A float32 column read as a double holds the shortest decimal of the
            // float (specs/data-tables.md §7.1).
            if (f.Kind == Kind.Float && shape == "float64")
                widened.Add((type, name));
            return;
        }
        if (rest.StartsWith('.') && f.Kind == Kind.Table)
            Use(f.Table!, rest[1..], whole, shape);
        else
            Problems.Add($"{whole}: cannot follow {rest} into {type}.{name} ({f.Kind}{(f.Vector ? "[]" : "")})");
    }

    /// <summary>Marks every field of a type as used, and of the types its fields hold.</summary>
    private void UseAll(string type)
    {
        if (!whole.Add(type))
            return;
        var t = schema.Tables[type];
        if (!used.TryGetValue(type, out var u))
            used[type] = u = [];
        foreach (var f in t.Fields)
        {
            u.Add(f.Name);
            if (IsJson(t, f) && !masks.ContainsKey((type, f.Name)))
                masks[(type, f.Name)] = new SortedSet<string>(StringComparer.Ordinal);
            if (f.Kind == Kind.Table)
                UseAll(f.Table!);
        }
    }

    // A tuple position [1] reads one element: the mask keeps every element.
    private static string NormaliseIndexes(string p) => System.Text.RegularExpressions.Regex.Replace(p, @"\[\d+\]", "[]");

    private bool IsJson(TableType t, Field f) =>
        f.Kind == Kind.Json || f.Kind == Kind.String && !f.Vector && !f.Map && jsonFields.Contains((t.Name, f.Name));

    /// <summary>Walks the table's JSON with its schema and notes string fields holding JSON.</summary>
    private void Scan(string table)
    {
        string path = Path.Combine(binData, table + ".json");
        if (!File.Exists(path))
        {
            Problems.Add($"{table}: {path} not found");
            return;
        }
        using var doc = JsonDocument.Parse(File.ReadAllBytes(path), new JsonDocumentOptions { MaxDepth = 512 });
        foreach (var row in doc.RootElement.EnumerateArray())
            ScanRow(schema.Tables[table], row);
    }

    private void ScanRow(TableType type, JsonElement row)
    {
        if (row.ValueKind != JsonValueKind.Object)
            return;
        foreach (var f in type.Fields)
        {
            if (!row.TryGetProperty(f.Name, out var v))
                continue;
            if (f.Kind == Kind.String && !f.Vector && !f.Map && v.ValueKind != JsonValueKind.String)
                jsonFields.Add((type.Name, f.Name));
            if (f.Kind == Kind.Table && !f.Map)
            {
                var sub = schema.Tables[f.Table!];
                if (f.Vector && v.ValueKind == JsonValueKind.Array)
                    foreach (var e in v.EnumerateArray())
                        ScanRow(sub, e);
                else
                    ScanRow(sub, v);
            }
        }
    }

    private static string Member(TableType type, Field f)
    {
        string n = f.Name;
        if (n == type.Name || n is "Fields" or "TypeName" or "IgnoresUnknownFields" || n == "Equals" || n == "GetHashCode" || n == "ToString" || n == "GetType")
            n += "_";
        return Keywords.Contains(n) ? "@" + n : n;
    }

    private static string MaskName(string type, string field) => $"{type}_{field}_Mask";

    /// <summary>The C# type and codec of one value of the field (an element, for vectors).</summary>
    private (string Type, string Codec) Scalar(TableType owner, Field f)
    {
        if (!f.Vector && !f.Map && IsJson(owner, f))
            return masks.TryGetValue((owner.Name, f.Name), out var m) && m.Count > 0
                ? ("JsonValue", $"MaskedJsonC<{MaskName(owner.Name, f.Name)}>")
                : ("JsonValue", "JsonC");
        return f.Kind switch
        {
            Kind.Bool => ("bool", "BoolC"),
            Kind.Byte or Kind.SByte or Kind.Short or Kind.Int => ("int", "IntC"),
            Kind.Long => ("long", "LongC"),
            Kind.Float when widened.Contains((owner.Name, f.Name)) => ("double", "FloatAsDoubleC"),
            Kind.Float => ("float", "FloatC"),
            Kind.Double => ("double", "DoubleC"),
            Kind.String => ("string", "StringC"),
            Kind.Table => (f.Table! + "?", $"TableC<{f.Table}>"),
            Kind.Json => ("JsonValue", "JsonC"),
            _ => throw new InvalidDataException(f.Kind.ToString()),
        };
    }

    private (string Type, string Codec, string Init) FieldType(TableType owner, Field f)
    {
        if (f.Map)
        {
            var entry = schema.Tables[f.Table!];
            var key = entry.Fields.First(e => e.Name == "Key");
            var value = entry.Fields.First(e => e.Name == "Value");
            var (kt, kc) = Scalar(entry, key with { Vector = false });
            var (vt, vc) = Scalar(entry, value with { Vector = false });
            if (value.Vector)
                (vt, vc) = (vt + "[]", $"ArrayC<{vt}, {vc}>");
            return ($"Map<{kt}, {vt}>", $"MapC<{kt}, {kc}, {vt}, {vc}>", $"Map<{kt}, {vt}>.Empty");
        }
        var (t, c) = Scalar(owner, f);
        if (f.Vector)
            return (t + "[]", $"ArrayC<{t}, {c}>", "[]");
        string init = t switch
        {
            "string" => "\"\"",
            "JsonValue" => "JsonValue.Null",
            _ => "",
        };
        return (t, c, init);
    }

    private void WriteType(StringBuilder sb, TableType type)
    {
        var fields = type.Fields.Where(f => used[type.Name].Contains(f.Name)).ToList();
        sb.Append($"\npublic sealed class {type.Name} : IRow<{type.Name}>\n{{\n");
        sb.Append($"    public static string TypeName => \"{type.Name}\";\n");
        // Every type reads only some of the JSON's fields.
        sb.Append("    public static bool IgnoresUnknownFields => true;\n");
        foreach (var f in fields)
        {
            var (t, _, init) = FieldType(type, f);
            sb.Append($"    public {t} {Member(type, f)}{(init.Length > 0 ? " = " + init : "")};\n");
        }
        sb.Append("\n    public void Fields<V>(ref V v) where V : struct, IFieldVisitor\n    {\n");
        foreach (var f in fields)
        {
            var (t, c, _) = FieldType(type, f);
            sb.Append($"        v.Field<{t}, {c}>(\"{f.Name}\", ref {Member(type, f)});\n");
        }
        sb.Append("    }\n}\n");
    }

    private static void WriteMask(StringBuilder sb, string type, string field, SortedSet<string> paths)
    {
        if (paths.Count == 0)
            return;
        sb.Append($"\n/// <summary>The paths the server reads in {type}.{field}.</summary>\n");
        sb.Append($"public readonly struct {MaskName(type, field)} : IJsonMask\n{{\n");
        sb.Append("    public static JsonMask Mask { get; } = JsonMask.Parse(\"\"\"\n");
        foreach (var p in paths)
            sb.Append("        ").Append(p).Append('\n');
        sb.Append("        \"\"\");\n}\n");
    }

    private void WriteDataTables(StringBuilder sb, List<(string Table, string Key)> tables)
    {
        sb.Append("\n/// <summary>The tables the server loads (specs/data-tables.tsv), each with its rows in table\n" +
            "/// order and an index by its key column in which a repeated key keeps its last row.</summary>\n" +
            "public sealed partial class DataTables\n{\n");
        foreach (var (t, key) in tables)
        {
            sb.Append($"    public {t}[] {t} = [];\n");
            if (!ByHand.Contains(t))
                sb.Append($"    public Dictionary<{KeyType(t, key)}, {t}> {t}By{key} = [];\n");
        }
        sb.Append("\n    public static readonly string[] Names =\n    [\n");
        foreach (var (t, _) in tables)
            sb.Append($"        \"{t}\",\n");
        sb.Append("    ];\n\n    private static readonly TableSlot[] Slots =\n    [\n");
        foreach (var (t, key) in tables)
        {
            string member = Member(schema.Tables[t], schema.Tables[t].Fields.First(f => f.Name == key));
            string index = ByHand.Contains(t) ? $"d.Index{t}()" : $"d.{t}By{key} = Index(rows, r => r.{member})";
            sb.Append($"        Slot<{t}>(\"{t}\", d => d.{t}, (d, rows) => {{ d.{t} = rows; {index}; }}),\n");
        }
        sb.Append("    ];\n}\n");
    }

    private string KeyType(string table, string key)
    {
        var type = schema.Tables[table];
        return FieldType(type, type.Fields.First(f => f.Name == key)).Type;
    }

    private static string GoField(Field f)
    {
        string n = f.Name;
        if (n is "Fields" or "TypeName" or "IgnoresUnknownFields" || GoKeywords.Contains(n))
            return n + "_";
        return n;
    }

    private (string Type, string Codec) GoScalar(TableType owner, Field f)
    {
        if (!f.Vector && !f.Map && IsJson(owner, f))
            return masks.TryGetValue((owner.Name, f.Name), out var m) && m.Count > 0
                ? ("Value", $"Masked({MaskName(owner.Name, f.Name)})")
                : ("Value", "JSONC");
        return f.Kind switch
        {
            Kind.Bool => ("bool", "BoolC"),
            Kind.Byte or Kind.SByte or Kind.Short or Kind.Int => ("int32", "IntC"),
            Kind.Long => ("int64", "LongC"),
            Kind.Float when widened.Contains((owner.Name, f.Name)) => ("float64", "FloatAsDoubleC"),
            Kind.Float => ("float32", "FloatC"),
            Kind.Double => ("float64", "DoubleC"),
            Kind.String => ("string", "StringC"),
            Kind.Table => ("*" + f.Table!, $"TableOf[{f.Table}]()"),
            Kind.Json => ("Value", "JSONC"),
            _ => throw new InvalidDataException(f.Kind.ToString()),
        };
    }

    private (string Type, string Codec) GoFieldType(TableType owner, Field f)
    {
        if (f.Map)
        {
            var entry = schema.Tables[f.Table!];
            var key = entry.Fields.First(e => e.Name == "Key");
            var value = entry.Fields.First(e => e.Name == "Value");
            var (kt, kc) = GoScalar(entry, key with { Vector = false });
            var (vt, vc) = GoScalar(entry, value with { Vector = false });
            if (value.Vector)
                (vt, vc) = ("[]" + vt, $"ArrayOf({vc})");
            return ($"*Map[{kt}, {vt}]", $"MapOf({kc}, {vc})");
        }
        var (t, c) = GoScalar(owner, f);
        return f.Vector ? ("[]" + t, $"ArrayOf({c})") : (t, c);
    }

    private string GoKeyType(string table, string key)
    {
        var type = schema.Tables[table];
        return GoFieldType(type, type.Fields.First(f => f.Name == key)).Type;
    }

    private void WriteGoType(StringBuilder sb, TableType type)
    {
        var fields = type.Fields.Where(f => used[type.Name].Contains(f.Name)).ToList();
        if (fields.Count == 0)
        {
            sb.Append($"type {type.Name} struct{{}}\n\n");
        }
        else
        {
            sb.Append($"type {type.Name} struct {{\n");
            int pad = fields.Max(f => GoField(f).Length);
            foreach (var f in fields)
            {
                string member = GoField(f);
                var (t, _) = GoFieldType(type, f);
                sb.Append('\t').Append(member).Append(' ', pad - member.Length + 1).Append(t).Append('\n');
            }
            sb.Append("}\n\n");
        }
        // go/printer keeps a one-statement func on one line when header + body <= 100 bytes,
        // and aligns the opening braces of adjacent one-line methods.
        string tnHeader = $"func (*{type.Name}) TypeName() string";
        string tnBody = $"return \"{type.Name}\"";
        string igHeader = $"func (*{type.Name}) IgnoresUnknownFields() bool";
        const string igBody = "return true";
        bool tnOneLine = tnHeader.Length + tnBody.Length <= 100;
        bool igOneLine = igHeader.Length + igBody.Length <= 100;
        if (tnOneLine && igOneLine)
        {
            sb.Append(tnHeader).Append(' ', igHeader.Length - tnHeader.Length + 1).Append("{ ").Append(tnBody).Append(" }\n");
            sb.Append(igHeader).Append(" { ").Append(igBody).Append(" }\n");
        }
        else
        {
            if (tnOneLine)
                sb.Append(tnHeader).Append(" { ").Append(tnBody).Append(" }\n");
            else
                sb.Append(tnHeader).Append(" {\n\t").Append(tnBody).Append("\n}\n");
            if (igOneLine)
                sb.Append(igHeader).Append(" { ").Append(igBody).Append(" }\n");
            else
                sb.Append(igHeader).Append(" {\n\t").Append(igBody).Append("\n}\n");
        }
        sb.Append($"func (r *{type.Name}) Fields(v Visitor) {{\n");
        foreach (var f in fields)
        {
            var (_, c) = GoFieldType(type, f);
            sb.Append($"\tF(v, \"{f.Name}\", &r.{GoField(f)}, {c})\n");
        }
        sb.Append("}\n\n");
    }

    private static void WriteGoMask(StringBuilder sb, string type, string field, SortedSet<string> paths)
    {
        if (paths.Count == 0)
            return;
        sb.Append($"var {MaskName(type, field)} = ParseMask(`\n");
        foreach (var p in paths)
            sb.Append("        ").Append(p).Append('\n');
        sb.Append("        `)\n\n");
    }

    private void WriteGoDataTables(StringBuilder sb, List<(string Table, string Key)> tables)
    {
        sb.Append("// DataTables holds every table of specs/data-tables.tsv, in its order, and the key indexes.\n");
        sb.Append("type DataTables struct {\n");
        sb.Append("\tLoads    []TableLoad\n");
        sb.Append("\tLoadTime time.Duration\n");
        sb.Append("\tlevelEntityIndex\n");
        var entries = new List<(string Name, string Type)>(tables.Count * 2);
        foreach (var (t, _) in tables)
            entries.Add((t, $"[]*{t}"));
        foreach (var (t, key) in tables)
            if (!ByHand.Contains(t))
                entries.Add(($"{t}By{key}", $"map[{GoKeyType(t, key)}]*{t}"));
        if (entries.Count > 0)
        {
            int pad = entries.Max(e => e.Name.Length);
            foreach (var (name, type) in entries)
                sb.Append('\t').Append(name).Append(' ', pad - name.Length + 1).Append(type).Append('\n');
        }
        sb.Append("}\n\n");
        sb.Append("// Names are the tables in list order.\nvar Names = []string{\n");
        foreach (var (t, _) in tables)
            sb.Append($"\t\"{t}\",\n");
        sb.Append("}\n\nvar slots = []slot{\n");
        foreach (var (t, key) in tables)
        {
            string getHeader = $"func(d *DataTables) []*{t}";
            string getBody = $"return d.{t}";
            string getter = getHeader.Length + getBody.Length <= 100
                ? $"{getHeader} {{ {getBody} }}"
                : $"{getHeader} {{\n\t\t{getBody}\n\t}}";
            string setHeader = $"func(d *DataTables, rows []*{t})";
            string stmt1 = $"d.{t} = rows";
            string stmt2;
            if (ByHand.Contains(t))
            {
                stmt2 = $"d.index{t}()";
            }
            else
            {
                var keyField = schema.Tables[t].Fields.First(f => f.Name == key);
                string kt = GoFieldType(schema.Tables[t], keyField).Type;
                string keyHeader = $"func(r *{t}) {kt}";
                string keyBody = $"return r.{GoField(keyField)}";
                string keyFunc = keyHeader.Length + keyBody.Length <= 100
                    ? $"{keyHeader} {{ {keyBody} }}"
                    : $"{keyHeader} {{\n\t\t\t{keyBody}\n\t\t}}";
                stmt2 = $"d.{t}By{key} = index(rows, {keyFunc})";
            }
            bool setOneLine = !stmt2.Contains('\n') && setHeader.Length + stmt1.Length + 2 + stmt2.Length <= 100;
            string setter = setOneLine
                ? $"{setHeader} {{ {stmt1}; {stmt2} }}"
                : $"{setHeader} {{\n\t\t{stmt1}\n\t\t{stmt2}\n\t}}";
            sb.Append($"\ttableSlot[{t}](\"{t}\", {getter}, {setter}),\n");
        }
        sb.Append("}\n");
    }
}
