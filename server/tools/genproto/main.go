// genproto writes the Go package server/protocol from the client's protocol as
// tools/Tidelab.ProtoGen left it in server/protocol (proto/*.proto, schema.tsv): protoc +
// protoc-gen-go compile proto/*.proto into one Go package, and schema.tsv's id rows become msgid.go.
//
//	go run ./tools/genproto [-protoc path] [-src protocol] [-out protocol]
//
// protoc-gen-go must be on PATH (go install google.golang.org/protobuf/cmd/protoc-gen-go@v1.36.12).
package main

import (
	"bufio"
	"flag"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"sort"
	"strconv"
	"strings"
)

func main() {
	protoc := flag.String("protoc", "", "protoc executable (default: PATH, else NuGet Grpc.Tools)")
	src := flag.String("src", "protocol", "directory with proto/ and schema.tsv")
	out := flag.String("out", "protocol", "output package directory")
	flag.Parse()
	bin := *protoc
	if bin == "" {
		var err error
		bin, err = findProtoc()
		if err != nil {
			fmt.Fprintln(os.Stderr, "genproto:", err)
			os.Exit(1)
		}
	}
	if err := run(bin, *src, *out); err != nil {
		fmt.Fprintln(os.Stderr, "genproto:", err)
		os.Exit(1)
	}
}

func findProtoc() (string, error) {
	if p, err := exec.LookPath("protoc"); err == nil {
		return p, nil
	}
	home, _ := os.UserHomeDir()
	plat, exe := "windows_x64", "protoc.exe"
	switch runtime.GOOS {
	case "linux":
		plat, exe = "linux_x64", "protoc"
	case "darwin":
		plat, exe = "macosx_x64", "protoc"
	}
	matches, _ := filepath.Glob(filepath.Join(home, ".nuget", "packages", "grpc.tools", "*", "tools", plat, exe))
	if len(matches) > 0 {
		sort.Strings(matches)
		return matches[len(matches)-1], nil
	}
	return "", fmt.Errorf("protoc not found on PATH or in %s/.nuget/packages/grpc.tools (run `dotnet restore tools/Tidelab.Tools.slnx` or pass -protoc)", home)
}

func extraPluginDirs() []string {
	var dirs []string
	if gp := os.Getenv("GOPATH"); gp != "" {
		dirs = append(dirs, filepath.Join(gp, "bin"))
	}
	if home, err := os.UserHomeDir(); err == nil {
		dirs = append(dirs, filepath.Join(home, "go", "bin"))
	}
	if local := os.Getenv("LOCALAPPDATA"); local != "" {
		dirs = append(dirs, filepath.Join(local, "Programs", "go-sdk", "bin"))
	}
	return dirs
}

func run(protoc, src, out string) error {
	protoDir := filepath.Join(src, "proto")
	files, err := filepath.Glob(filepath.Join(protoDir, "*.proto"))
	if err != nil || len(files) == 0 {
		return fmt.Errorf("no .proto files in %s", protoDir)
	}
	old, _ := filepath.Glob(filepath.Join(out, "*.pb.go"))
	for _, f := range old {
		if err := os.Remove(f); err != nil {
			return err
		}
	}
	// Every file goes to one Go package: the proto packages import each other in a cycle
	// (aki.protocol <-> aki.protocol.ai), and no two top-level names clash.
	args := []string{"-I" + protoDir, "--go_out=" + out, "--go_opt=paths=source_relative"}
	names := make([]string, 0, len(files))
	for _, f := range files {
		names = append(names, filepath.Base(f))
	}
	sort.Strings(names)
	for _, n := range names {
		args = append(args, "--go_opt=M"+n+"=tidelab/protocol")
	}
	args = append(args, names...)
	cmd := exec.Command(protoc, args...)
	env := os.Environ()
	var add []string
	for _, d := range extraPluginDirs() {
		if st, err := os.Stat(d); err == nil && st.IsDir() {
			add = append(add, d)
		}
	}
	if len(add) > 0 {
		pathEnv := os.Getenv("PATH")
		joined := strings.Join(add, string(os.PathListSeparator)) + string(os.PathListSeparator) + pathEnv
		updated := false
		for i, kv := range env {
			if strings.HasPrefix(strings.ToUpper(kv), "PATH=") {
				env[i] = "PATH=" + joined
				updated = true
				break
			}
		}
		if !updated {
			env = append(env, "PATH="+joined)
		}
	}
	cmd.Env = env
	cmd.Stdout, cmd.Stderr = os.Stdout, os.Stderr
	if err := cmd.Run(); err != nil {
		return fmt.Errorf("protoc: %w", err)
	}
	return writeIDs(filepath.Join(src, "schema.tsv"), filepath.Join(out, "msgid.go"))
}

func writeIDs(schema, path string) error {
	f, err := os.Open(schema)
	if err != nil {
		return err
	}
	defer f.Close()
	type id struct {
		name string
		num  int
	}
	var ids []id
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		cols := strings.Split(strings.TrimRight(sc.Text(), "\r"), "\t")
		if len(cols) == 3 && cols[0] == "id" {
			n, err := strconv.Atoi(cols[2])
			if err != nil || n < 0 || n > 0xFFFF {
				return fmt.Errorf("schema.tsv: bad id row %q", sc.Text())
			}
			ids = append(ids, id{cols[1], n})
		}
	}
	if err := sc.Err(); err != nil {
		return err
	}
	sort.Slice(ids, func(i, j int) bool { return ids[i].num < ids[j].num })
	var b strings.Builder
	b.WriteString("// Code generated by tools/genproto from schema.tsv (the client's Aki.Protocol.EMessageId). DO NOT EDIT.\n\n")
	b.WriteString("package protocol\n\n")
	b.WriteString("// MessageID is the client's message id: a u16 in every frame (specs/network.md).\n")
	b.WriteString("type MessageID uint16\n\n")
	b.WriteString("const (\n")
	for _, i := range ids {
		fmt.Fprintf(&b, "\tID%s MessageID = %d\n", i.name, i.num)
	}
	b.WriteString(")\n\n")
	b.WriteString("// messageNames maps each id to its message's short name.\n")
	b.WriteString("var messageNames = map[MessageID]string{\n")
	for _, i := range ids {
		fmt.Fprintf(&b, "\t%d: %q,\n", i.num, i.name)
	}
	b.WriteString("}\n")
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return err
	}
	return os.WriteFile(path, src, 0o644)
}
